#!/usr/bin/env python3
"""
Generate a text-only watermark SVG with the text baked in as glyph outline paths.

Why paths: SVG <text> is rasterised with whatever font the *server* has, so the
mark would differ between machines. Outlines render identically everywhere and
need no fonts at runtime. The bundled DejaVu Sans Bold makes the output
reproducible on any machine; pass --font to use another TTF/OTF.

Usage (from the project root):
    npm run watermark -- --text "MY BRAND"
    python3 tools/make-watermark.py --text "MY BRAND" [--size 44] [--stroke 2]
        [--letter-spacing 2] [--fill "#f6f5f1"] [--stroke-color "#1f2933"]
        [--font path/to/font.ttf] [--out public/watermark.svg]

Requires: python3 and fonttools (pip install fonttools).
The server reads public/watermark.svg on every request: no restart needed.
"""
import argparse
import math
import os
import sys
from xml.sax.saxutils import escape

try:
    from fontTools.ttLib import TTFont
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
except ImportError:
    sys.exit("fonttools is required: pip install fonttools")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_FONT = os.path.join(HERE, "fonts", "DejaVuSans-Bold.ttf")
DEFAULT_OUT = os.path.join(ROOT, "public", "watermark.svg")


def parse_args(argv):
    p = argparse.ArgumentParser(description="Generate a text-only watermark SVG (glyph outlines, no font needed at runtime).")
    p.add_argument("--text", default="SHARP VIEWER", help='watermark text (default: "SHARP VIEWER", the stock mark)')
    p.add_argument("--font", default=DEFAULT_FONT, help="TTF/OTF font file (default: bundled DejaVu Sans Bold)")
    p.add_argument("--size", type=float, default=44, help="font size in px at native scale (default 44; only the aspect ratio matters, wmWidth/wmHeight set the final size)")
    p.add_argument("--letter-spacing", type=float, default=2, help="extra space between glyphs, px (default 2)")
    p.add_argument("--stroke", type=float, default=2, help="outline width, px; 0 for none (default 2)")
    p.add_argument("--fill", default="#f6f5f1", help="text colour (default #f6f5f1)")
    p.add_argument("--stroke-color", default="#1f2933", help="outline colour (default #1f2933)")
    p.add_argument("--out", default=DEFAULT_OUT, help="output file (default: public/watermark.svg, the mark the server uses)")
    return p.parse_args(argv)


def build_svg(text, font_path, size, letter_spacing, stroke, fill, stroke_color):
    if not text.strip():
        raise ValueError("text must not be empty or whitespace only")
    if size <= 0:
        raise ValueError("size must be > 0")
    if stroke < 0:
        raise ValueError("stroke must be >= 0")

    font = TTFont(font_path)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = size / font["head"].unitsPerEm

    missing = sorted({ch for ch in text if ord(ch) not in cmap and not ch.isspace()})
    if missing:
        raise ValueError(f"font {os.path.basename(font_path)} has no glyph for: {' '.join(repr(c) for c in missing)}")

    pen = SVGPathPen(glyph_set)
    bounds = BoundsPen(glyph_set)
    x = 0.0
    for ch in text:
        glyph = glyph_set[cmap.get(ord(ch), font.getBestCmap().get(ord(" ")))]
        t = (scale, 0, 0, -scale, x, 0)  # scale to px, flip y (SVG y grows downward), advance x
        glyph.draw(TransformPen(pen, t))
        glyph.draw(TransformPen(bounds, t))
        x += glyph.width * scale + letter_spacing

    d = pen.getCommands()
    if bounds.bounds is None:
        raise ValueError("text produced no visible glyphs")
    xmin, ymin, xmax, ymax = bounds.bounds
    # Expand by half the stroke, then snap to whole pixels: integer-sized canvas, cropped to the paint.
    xmin = math.floor(xmin - stroke / 2); ymin = math.floor(ymin - stroke / 2)
    xmax = math.ceil(xmax + stroke / 2); ymax = math.ceil(ymax + stroke / 2)
    w, h = xmax - xmin, ymax - ymin

    svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="{xmin} {ymin} {w} {h}">',
           f'  <!-- Watermark: "{escape(text)}" as glyph outlines (no font needed), text only, no background.',
           f'       Generated by tools/make-watermark.py from {escape(os.path.basename(font_path))} at {size:g}px. -->',
           '  <g id="mark">']
    if stroke:
        svg.append(f'    <path d="{d}" fill="none" stroke="{escape(stroke_color)}" stroke-width="{stroke:g}" stroke-linejoin="round"/>')
    svg.append(f'    <path d="{d}" fill="{escape(fill)}"/>')
    svg += ['  </g>', '</svg>', '']
    return "\n".join(svg), w, h


def main(argv=None):
    a = parse_args(argv)
    try:
        svg, w, h = build_svg(a.text, a.font, a.size, a.letter_spacing, a.stroke, a.fill, a.stroke_color)
    except (ValueError, OSError) as e:
        sys.exit(f"error: {e}")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)) or ".", exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(svg)
    rel = os.path.relpath(a.out)
    print(f'wrote {rel}: "{a.text}" -> canvas {w}x{h} (aspect {w / h:.2f}:1), stroke {a.stroke:g}px')
    print(f"  e.g. wmWidth=200 -> 200x{round(200 * h / w)}, wmWidth=300 -> 300x{round(300 * h / w)}, wmHeight=40 -> {round(40 * w / h)}x40")
    if os.path.abspath(a.out) == os.path.abspath(DEFAULT_OUT):
        print("  this is the mark the server uses; reload the page (no restart needed)")


if __name__ == "__main__":
    main()
